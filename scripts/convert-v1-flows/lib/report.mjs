/**
 * The conversion report (design D8, task 5.2).
 *
 * A 456-bundle diff cannot be reviewed file by file, so the report is how the
 * change is read: per-rule counts, every dropped file with its reason, every
 * transformed value, and the evidence later changes need.
 *
 * Two rules are deliberately reported as applied 0 times. §46 names three
 * defects to fix and only one exists in this source; a report that omitted the
 * other two would read as though they had been fixed.
 */

import { TRANSFORM_RULE_NAMES } from "./rules.mjs"
import { ASSERTION_RULE_NAMES } from "./assertions.mjs"

const h2 = (text) => `## ${text}\n`
const h3 = (text) => `### ${text}\n`

function table(headers, rows) {
  if (rows.length === 0) return "_None._\n"
  const head = `| ${headers.join(" | ")} |`
  const rule = `| ${headers.map(() => "---").join(" | ")} |`
  const body = rows.map((row) => `| ${row.join(" | ")} |`).join("\n")
  return `${head}\n${rule}\n${body}\n`
}

const code = (value) => `\`${value}\``
const mb = (bytes) => `${(bytes / 1048576).toFixed(1)} MB`

/**
 * Show a pair of values so the DIFFERENCE is visible.
 *
 * Truncating two long strings from the left shows two identical-looking
 * prefixes — which is exactly wrong for a table whose job is to show what
 * changed. So the shared prefix and suffix are elided and the window is centred
 * on the first divergence.
 */
export function excerptPair(a, b, width = 70) {
  const left = JSON.stringify(a) ?? "undefined"
  const right = JSON.stringify(b) ?? "undefined"

  if (left.length <= width && right.length <= width) return [left, right]

  let prefix = 0
  while (
    prefix < left.length &&
    prefix < right.length &&
    left[prefix] === right[prefix]
  ) {
    prefix += 1
  }

  let suffix = 0
  while (
    suffix < left.length - prefix &&
    suffix < right.length - prefix &&
    left[left.length - 1 - suffix] === right[right.length - 1 - suffix]
  ) {
    suffix += 1
  }

  const window = (value) => {
    const start = Math.max(0, prefix - 12)
    const end = Math.min(value.length, value.length - suffix + 12)
    const body = value.slice(start, end)
    return `${start > 0 ? "…" : ""}${body}${end < value.length ? "…" : ""}`
  }

  return [window(left), window(right)]
}

/**
 * Render the report.
 *
 * Takes only already-collected facts: the report states what happened, it does
 * not re-derive it, so it cannot disagree with the pack it describes.
 */
export function renderReport({
  sourceRoot,
  counts,
  drops,
  divergences = [],
  transforms,
  passMarks,
  bespoke,
  vocabularies,
  governance,
  reservedAnswerKeyPaths,
  sizes,
  verification,
  orphansRemoved,
  subjectRefCollisions,
}) {
  const sections = []

  sections.push(
    `# Conversion report — v1 flows → claims pack\n`,
    `Generated by ${code("pnpm packs:convert-v1")} from v1's flow bundles. This file is the\n` +
      `account of how ${code("packs/claims/flows/")} was produced: what was carried, what was\n` +
      `dropped and why, and the evidence later changes depend on. Reviewing the conversion\n` +
      `means reading this and spot-checking the diff.\n\n` +
      `Source: ${code(sourceRoot)}\n`
  )

  // ---------------------------------------------------------------- inventory
  sections.push(
    h2("Inventory"),
    table(
      ["", "Count"],
      [
        ["Flow groups", counts.flows],
        ["Bundles (base + variant)", counts.bundles],
        ["Variant directories", counts.variantDirectories],
        ["Subject refs", counts.subjectRefs],
        ["Files written", counts.filesWritten],
        ["Files dropped", drops.length],
      ]
    ),
    `\nThe source holds **${counts.flows}** flow groups, not the 93 cited in §5, §46 and\n` +
      `${code("packs/claims/README.md")}. v1's registry exports ${counts.flows} ` +
      `${code("flow<NNNN>Variants")} and there are ${counts.flows} ${code("index.ts")} modules;\n` +
      `code is authoritative over the spec.\n`
  )

  // -------------------------------------------------------------- rule counts
  sections.push(h2("Rule counts"))
  sections.push(
    h3("Transforms"),
    table(
      ["Rule", "Applied"],
      TRANSFORM_RULE_NAMES.map((name) => [code(name), counts.rules[name] ?? 0])
    )
  )
  sections.push(
    h3("Assertions"),
    table(
      ["Rule", "Checked", "Violations"],
      ASSERTION_RULE_NAMES.map((name) => [
        code(name),
        counts.rules[name] ?? 0,
        0,
      ])
    ),
    `\n${code("assert-no-field-level-visible-when")} and ${code("assert-no-legacy-mode-key")} are\n` +
      `the two §46 fixes that are **no-ops on this source**: every ${code("visibleWhen")} is\n` +
      `section-level, and no ${code("state.json")} carries the legacy ${code("assignment")} key.\n` +
      `They are reported at their true count rather than omitted, and they fail the run if a\n` +
      `future v1 edit introduces either.\n`
  )

  // ------------------------------------------------------------------- drops
  const dropsByRule = {}
  for (const drop of drops) {
    ;(dropsByRule[drop.rule] ||= []).push(drop)
  }

  sections.push(
    h2("Dropped files"),
    table(
      ["Rule", "Files", "Reason"],
      Object.entries(dropsByRule).map(([rule, entries]) => [
        code(rule),
        entries.length,
        entries[0].reason,
      ])
    )
  )

  const dead = dropsByRule["drop-dead-variant-files"] ?? []
  if (dead.length) {
    sections.push(
      `\n${h3("Dead content — distinct but never served")}`,
      `These differ from their base, so a duplicate check alone would have carried them, but\n` +
        `v1's ${code("index.ts")} binds the base copy for that variant, so v1 never served them.\n` +
        `Dropping them preserves v1 behaviour exactly. They are listed in full because they\n` +
        `encode authoring intent that never ran, and reviving it would be a deliberate change.\n\n`,
      table(
        ["Path", "Reason"],
        dead.map((drop) => [
          code(drop.path),
          "distinct from base but unreachable in v1",
        ])
      )
    )
  }

  if (orphansRemoved?.length) {
    sections.push(
      `\n${h3("Removed as orphaned")}`,
      table(
        ["Path"],
        orphansRemoved.map((entry) => [code(entry.path)])
      )
    )
  }

  // ---------------------------------------------------- carried divergences
  sections.push(
    h2("Carried variant files, and what diverges in them"),
    `Every variant file carried for a reason other than ${code("data.json")} — which varies in\n` +
      `all 364 variants by design. These are the files the §13 departure turns on: a variant\n` +
      `keeps its own ${code("navigator.json")} or ${code("state.json")} only because v1 served\n` +
      `it and it genuinely differs. The diverging values are listed so the decision can be\n` +
      `checked rather than taken on trust.\n`
  )

  if (divergences.length === 0) {
    sections.push(`_None._\n`)
  } else {
    for (const divergence of divergences) {
      sections.push(
        h3(code(divergence.path)),
        table(
          ["Path", "Base", "This variant"],
          divergence.diffs.slice(0, 12).map((diff) => {
            const [base, variant] = excerptPair(diff.a, diff.b)
            return [code(diff.path), code(base), code(variant)]
          })
        ),
        divergence.diffs.length > 12
          ? `\n_…and ${divergence.diffs.length - 12} more._\n`
          : ""
      )
    }
  }

  // ------------------------------------------- defects needing a decision
  sections.push(
    h2("Defects carried over, needing an authoring decision"),
    `Pre-existing v1 content defects. Conversion neither fixes nor hides these: the fix is an\n` +
      `authoring decision, and inventing one would be the same mistake as inventing a\n` +
      `governance value.\n`
  )

  if (subjectRefCollisions?.length) {
    sections.push(
      h3("Subject refs claimed by more than one bundle"),
      `A subject ref should route to exactly one bundle. Where two claim it,\n` +
        `${code("resolveBundleSource(subject)")} is ambiguous and which bundle a trainee is served\n` +
        `depends on iteration order. Resolving it means renumbering one flow's claim.\n\n`,
      table(
        ["Subject ref", "Claimed by", "And by"],
        subjectRefCollisions.map((collision) => [
          code(collision.ref),
          code(collision.first),
          code(collision.second),
        ])
      )
    )
  } else {
    sections.push(
      h3("Subject refs claimed by more than one bundle"),
      `None — every subject ref routes to exactly one bundle.\n`
    )
  }

  const deadForDefects = dropsByRule["drop-dead-variant-files"] ?? []
  sections.push(
    h3("Authored content v1 never served"),
    deadForDefects.length
      ? `${deadForDefects.length} variant file(s) differ from their base but were never bound, ` +
          `listed under "Dead content" above. Reviving that intent would be a deliberate change.\n`
      : `None.\n`
  )

  // -------------------------------------------------------------- transforms
  const transformsByRule = {}
  for (const transform of transforms) {
    ;(transformsByRule[transform.rule] ||= []).push(transform)
  }

  sections.push(h2("Transformed values"))
  for (const [rule, entries] of Object.entries(transformsByRule)) {
    sections.push(
      h3(code(rule)),
      table(
        ["File", "Path", "From", "To"],
        entries.map((entry) => [
          code(entry.file),
          code(entry.path),
          code(JSON.stringify(entry.from)),
          code(entry.to === undefined ? "(removed)" : JSON.stringify(entry.to)),
        ])
      )
    )
  }

  // ------------------------------------------------------- governance evidence
  sections.push(
    h2("Governance evidence"),
    `Values this conversion refuses to invent (§45.3). Each ships as config with its default\n` +
      `marked **"not approved"**.\n`
  )

  sections.push(
    h3("Flow pass marks — evidence for the `pass_standards` seed"),
    `§45.2 moves v1's ${code("FLOW_PASS_MARK_PCT = 70")} to the governance-owned\n` +
      `${code("pass_standards")} surface, so ${code("passMark")} is stripped from every\n` +
      `${code("result.json")}. The observed values are recorded here as the evidence that seed\n` +
      `needs; whether flow pass marks stay at 70 is an open decision (§45.3).\n\n`,
    table(
      ["Observed pass mark", "Flows"],
      Object.entries(
        passMarks.reduce((acc, entry) => {
          const key = String(entry.passMark)
          acc[key] = (acc[key] ?? 0) + 1
          return acc
        }, {})
      ).map(([value, count]) => [value, count])
    ),
    `\n${passMarks
      .filter((entry) => entry.passMark !== 70)
      .map(
        (entry) =>
          `${code(entry.code)} observed ${code(String(entry.passMark))} — unscored demo flow.`
      )
      .join("\n")}\n`
  )

  sections.push(
    h3("Flow → week mapping"),
    `Not assigned. The claims flow → week mapping is an open decision (§45.3), so\n` +
      `${code("pack.json")} carries the surface present but unassigned with its default marked\n` +
      `**"not approved"**. No week, module or scenario is inferred from a flow code, directory\n` +
      `name or source comment. Weeks 9–10 cannot be populated until governance settles it, and\n` +
      `expressing it also needs the scenario → module mapping, which lives in the v1 database\n` +
      `rather than these files.\n`
  )

  if (governance?.notes?.length) {
    sections.push(
      table(
        ["Surface", "State"],
        governance.notes.map((note) => [note.surface, note.state])
      )
    )
  }

  // ------------------------------------------------------------- vocabularies
  sections.push(
    h2("Pack vocabularies"),
    `§5 makes decision keys and reason codes pack-authored. v1 held them in core code and in\n` +
      `bundles at once; conversion unifies them into ${code("pack.json")}.\n`,
    table(
      ["Vocabulary", "Codes"],
      [
        ["`decisionOptions`", vocabularies.decisionOptions.join(", ")],
        ["Reason codes", vocabularies.reasonCodeCount],
        ["PX edit bypass codes", vocabularies.bypassCodeCount],
      ]
    )
  )

  sections.push(
    `\n${code("decisionOptions")} has **three** keys, not the two §5 cites. 87 flows offer\n` +
      `${code("[pay, deny]")}; 5 also offer ${code("pend")}. No rubric expects ${code("pend")},\n` +
      `so it is a distractor — and it must still be declared, because the server validates a\n` +
      `submitted decision against this list and a trainee who picks the distractor has to be\n` +
      `scored wrong rather than refused.\n`
  )

  if (vocabularies.drift) {
    const { authoredNotInCatalog, catalogNeverAuthored, missingLabels } =
      vocabularies.drift
    sections.push(
      h3("Drift this unification removes"),
      `v1 split the reason-code vocabulary between ${code("REJECT_CODE_CATALOG")} in\n` +
        `${code("packages/shared")} and the codes bundles author. v1's own comment concedes the\n` +
        `drift: "a code missing here is still offered, labelled by its code".\n\n`,
      table(
        ["Drift", "Codes"],
        [
          [
            "Authored by a bundle, missing from v1's catalog",
            authoredNotInCatalog.map(code).join(", ") || "none",
          ],
          [
            "In v1's catalog, never authored (distractor only)",
            catalogNeverAuthored.map(code).join(", ") || "none",
          ],
          [
            "Still missing a label",
            missingLabels.map(code).join(", ") || "none",
          ],
        ]
      )
    )
  }

  sections.push(
    h3("Reject-code minimum is server-side padding"),
    `§14.1's ${code("MIN_REJECT_CODE_OPTIONS = 5")} is **not** a bundle constraint. A flow\n` +
      `authors only the codes it expects — 1 to 3 of them, and all 23 deny flows are under 5 —\n` +
      `and the server pads the offered list from the pack's pool and shuffles, so a\n` +
      `single-option picker cannot give the answer away. Asserting the count against bundles\n` +
      `would have failed every deny flow in the pack.\n`
  )

  // ----------------------------------------------------------------- bespoke
  sections.push(
    h2("Bespoke sub-tab bindings"),
    `No v1 ${code("ui.json")} carries a ${code("component")} key: v1 binds sub-tab ids to\n` +
      `components in a web-app map, so which component renders a sub-tab was invisible to the\n` +
      `pack — §14.2's defect. Conversion writes the binding into the converted ${code("ui.json")}.\n\n` +
      `${code("dataPath")} values are **observed candidates**, not a declared contract: the\n` +
      `components document their paths in prose. They are the evidence the §14.2 registry needs,\n` +
      `and an empty list means the component reads the whole ${code("data")} blob rather than a\n` +
      `named path.\n`,
    table(
      ["Sub-tab id", "Component", "Observed dataPath candidates"],
      bespoke.bindings.map((binding) => [
        code(binding.subTabId),
        code(binding.component),
        binding.dataPathCandidates.length
          ? binding.dataPathCandidates.map(code).join(", ")
          : "_(reads the whole data blob)_",
      ])
    )
  )

  // -------------------------------------------------------- reserved answer keys
  sections.push(
    h2("Reserved answer-key paths"),
    `${code("data.json")} is served to trainees, so an answer key loose in it would be a leak.\n` +
      `§13 assigns one reserved home — the randomization / mismatch block — and every\n` +
      `occurrence in this source sits there. Recorded so the trainee-role strip is known to\n` +
      `cover them.\n`,
    table(
      ["Path", "Occurrences"],
      Object.entries(
        reservedAnswerKeyPaths.reduce((acc, path) => {
          const generalized = path.replace(/\[\d+\]/g, "[N]")
          acc[generalized] = (acc[generalized] ?? 0) + 1
          return acc
        }, {})
      ).map(([path, count]) => [code(path), count])
    )
  )

  // -------------------------------------------------------------------- size
  sections.push(
    h2("Size"),
    `Dropping duplicates is what makes committing the pack tolerable. ${code("ui.json")} is the\n` +
      `bulk of the source and almost all of it was copies.\n`,
    table(
      ["", "Bytes"],
      [
        ["Source", mb(sizes.source)],
        ["Written", mb(sizes.written)],
        [
          "Dropped",
          `${mb(sizes.source - sizes.written)} (${Math.round((1 - sizes.written / sizes.source) * 100)}%)`,
        ],
      ]
    ),
    `\n`,
    table(
      ["File", "Written", "Dropped"],
      Object.entries(sizes.byFile).map(([file, entry]) => [
        code(file),
        mb(entry.written),
        mb(entry.dropped),
      ])
    )
  )

  // ------------------------------------------------------------ verification
  sections.push(
    h2("Verification"),
    `Re-read from disk after writing, not from the objects that produced the files, so a\n` +
      `serialization bug or a write that never landed is caught rather than assumed away.\n`,
    table(
      ["", "Count"],
      [
        ["Files parsed and checked", verification.filesVerified],
        ["Flows verified", verification.flowsVerified],
        ["Variant folders verified", verification.variantFoldersVerified],
      ]
    )
  )

  return `${sections.join("\n")}`
}
